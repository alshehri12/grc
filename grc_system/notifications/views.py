"""
Notifications app views.

Users only ever see their own notifications and reminders; escalations are
visible to the people involved (and to managers/admins). Templates are
admin-managed reference data.
"""
from django.db.models import Q
from django.utils import timezone
from django_filters.rest_framework import DjangoFilterBackend
from rest_framework import status
from rest_framework.decorators import action
from rest_framework.filters import SearchFilter, OrderingFilter
from rest_framework.response import Response

from core.audit import AuditedModelViewSet, log_action
from core.permissions import IsAdminOrReadOnly, user_is_admin, user_can_approve
from .models import NotificationTemplate, Notification, Reminder, Escalation
from .serializers import (
    NotificationTemplateSerializer, NotificationSerializer,
    ReminderSerializer, EscalationSerializer
)


class NotificationTemplateViewSet(AuditedModelViewSet):
    queryset = NotificationTemplate.objects.all()
    serializer_class = NotificationTemplateSerializer
    permission_classes = [IsAdminOrReadOnly]
    filter_backends = [DjangoFilterBackend, SearchFilter]
    filterset_fields = ['event_type', 'channel', 'is_active']
    search_fields = ['name', 'name_ar', 'code']


class NotificationViewSet(AuditedModelViewSet):
    queryset = Notification.objects.select_related('recipient', 'template').all()
    serializer_class = NotificationSerializer
    filter_backends = [DjangoFilterBackend, OrderingFilter]
    filterset_fields = ['status', 'channel', 'priority']
    ordering = ['-created_at']
    http_method_names = ['get', 'post', 'head', 'options']  # created by the system, read by users

    def get_queryset(self):
        qs = super().get_queryset()
        if user_is_admin(self.request.user) and self.request.query_params.get('all') == 'true':
            return qs
        return qs.filter(recipient=self.request.user)

    def create(self, request, *args, **kwargs):
        if not user_is_admin(request.user):
            return Response({'error': 'Notifications are generated by the system'}, status=status.HTTP_403_FORBIDDEN)
        return super().create(request, *args, **kwargs)

    @action(detail=False, methods=['get'])
    def my_notifications(self, request):
        notifications = self.get_queryset().filter(recipient=request.user)
        if request.query_params.get('unread') == 'true':
            notifications = notifications.filter(read_at__isnull=True)
        return Response(self.get_serializer(notifications[:50], many=True).data)

    @action(detail=False, methods=['get'])
    def unread_count(self, request):
        count = Notification.objects.filter(recipient=request.user, read_at__isnull=True).count()
        return Response({'count': count})

    @action(detail=True, methods=['post'])
    def mark_read(self, request, pk=None):
        notification = self.get_object()
        if notification.recipient_id != request.user.pk:
            return Response({'error': 'Not your notification'}, status=status.HTTP_403_FORBIDDEN)
        notification.read_at = timezone.now()
        notification.status = 'read'
        notification.save(update_fields=['read_at', 'status'])
        return Response(NotificationSerializer(notification).data)

    @action(detail=False, methods=['post'])
    def mark_all_read(self, request):
        Notification.objects.filter(recipient=request.user, read_at__isnull=True).update(
            read_at=timezone.now(), status='read')
        return Response({'status': 'success'})


class ReminderViewSet(AuditedModelViewSet):
    queryset = Reminder.objects.select_related('recipient', 'created_by').all()
    serializer_class = ReminderSerializer
    filter_backends = [DjangoFilterBackend, OrderingFilter]
    filterset_fields = ['status', 'frequency']
    ordering = ['scheduled_date']

    def get_queryset(self):
        qs = super().get_queryset()
        if user_is_admin(self.request.user):
            return qs
        return qs.filter(Q(recipient=self.request.user) | Q(created_by=self.request.user))

    def perform_create(self, serializer):
        serializer.validated_data.setdefault('created_by', self.request.user)
        serializer.validated_data.setdefault('recipient', self.request.user)
        return super().perform_create(serializer)


class EscalationViewSet(AuditedModelViewSet):
    queryset = Escalation.objects.select_related('escalated_from', 'escalated_to', 'resolved_by').all()
    serializer_class = EscalationSerializer
    filter_backends = [DjangoFilterBackend, OrderingFilter]
    filterset_fields = ['status', 'level', 'escalated_to']
    ordering = ['-escalated_at']
    http_method_names = ['get', 'post', 'head', 'options']

    def get_queryset(self):
        qs = super().get_queryset()
        if user_can_approve(self.request.user):
            return qs
        return qs.filter(Q(escalated_from=self.request.user) | Q(escalated_to=self.request.user))

    def create(self, request, *args, **kwargs):
        if not user_is_admin(request.user):
            return Response({'error': 'Escalations are generated by the system'}, status=status.HTTP_403_FORBIDDEN)
        return super().create(request, *args, **kwargs)

    @action(detail=True, methods=['post'])
    def resolve(self, request, pk=None):
        escalation = self.get_object()
        if not (user_is_admin(request.user) or escalation.escalated_to_id == request.user.pk):
            return Response({'error': 'Only the escalation recipient can resolve it'}, status=status.HTTP_403_FORBIDDEN)
        escalation.status = 'resolved'
        escalation.resolved_by = request.user
        escalation.resolved_at = timezone.now()
        escalation.resolution_notes = request.data.get('notes', '')
        escalation.save()
        log_action(request.user, 'update', escalation, changes={'status': ['pending', 'resolved']}, request=request)
        return Response(EscalationSerializer(escalation).data)
