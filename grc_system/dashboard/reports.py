def _risk_section(org):
    from risk.models import Risk, KeyRiskIndicator
    from risk.utils import get_risk_thresholds

    risks = Risk.objects.filter(organization=org).exclude(status='closed').select_related('category', 'owner')
    by_level = {'critical': 0, 'high': 0, 'medium': 0, 'low': 0}
    res_level = {'critical': 0, 'high': 0, 'medium': 0, 'low': 0}
    appetite = {'within': 0, 'tolerance': 0, 'breach': 0}
    outside = []
    for r in risks:
        by_level[r.risk_level] += 1
        if r.residual_risk_level:
            res_level[r.residual_risk_level] += 1
        a = r.appetite_status
        appetite[a['status']] += 1
        if a['status'] != 'within':
            outside.append((r, a))
    outside.sort(key=lambda x: -x[1]['excess'])
    t = get_risk_thresholds(org)

    story = [Paragraph('1. Risk Profile', H2)]
    story.append(_kv([('Open risks', risks.count()),
                      ('Inherent: critical / high / medium / low', ' / '.join(str(by_level[k]) for k in by_level)),
                      ('Residual: critical / high / medium / low', ' / '.join(str(res_level[k]) for k in res_level)),
                      ('Within appetite / outside (tolerance) / above tolerance',
                       f"{appetite['within']} / {appetite['tolerance']} / {appetite['breach']}"),
                      ('Risk matrix thresholds', f"medium >= {t['medium']}, high >= {t['high']}, critical >= {t['critical']}")]))
    story.append(Spacer(1, 6))
    story.append(Paragraph('Risks outside appetite (require treatment or escalation)', BODY))
    rows = [(r.risk_id, r.title, r.category.name if r.category else '-', a['score'], a['appetite'], a['tolerance'],
             a['status'].upper(), r.owner.get_full_name() if r.owner else '-',
             r.treatments.filter(status__in=['planned', 'in_progress']).count()) for r, a in outside[:25]]
    story.append(_table(['ID', 'Risk', 'Category', 'Score', 'Appetite', 'Tolerance', 'Status', 'Owner', 'Active treatments'],
                        rows, [2.0 * cm, 4.6 * cm, 2.2 * cm, 1.2 * cm, 1.5 * cm, 1.6 * cm, 1.9 * cm, 2.4 * cm, 1.6 * cm],
                        status_col=6, color_map={'breach': '#F44336', 'tolerance': '#FF9800'}))

    story.append(Spacer(1, 8))
    story.append(Paragraph('Top risks by residual exposure', BODY))
    top = sorted(risks, key=lambda r: -(r.residual_risk_score or r.inherent_risk_score))[:15]
    rows = [(r.risk_id, r.title, r.get_risk_type_display(), f'{r.inherent_likelihood}x{r.inherent_impact}={r.inherent_risk_score}',
             f'{r.residual_likelihood}x{r.residual_impact}={r.residual_risk_score}' if r.residual_risk_score else '-',
             (r.residual_risk_level or r.risk_level), r.get_status_display(), r.owner.get_full_name() if r.owner else '-') for r in top]
    story.append(_table(['ID', 'Risk', 'Type', 'Inherent', 'Residual', 'Level', 'Status', 'Owner'], rows,
                        [2.0 * cm, 5.0 * cm, 2.0 * cm, 2.0 * cm, 2.0 * cm, 1.6 * cm, 2.0 * cm, 2.4 * cm],
                        status_col=5, color_map=LEVEL_COLORS))

    kris = KeyRiskIndicator.objects.filter(organization=org, is_active=True).select_related('risk', 'owner')
    if kris.exists():
        story.append(Spacer(1, 8))
        story.append(Paragraph('Key Risk Indicators', BODY))
        rows = [(k.kri_id, k.name, k.risk.risk_id if k.risk_id else '-',
                 f'{k.current_value}{k.unit}' if k.current_value is not None else '-',
                 f'{k.warning_threshold}/{k.critical_threshold}{k.unit}', k.current_status.upper(),
                 k.last_measured_at or '-', 'OVERDUE' if k.is_measurement_overdue else 'ok') for k in kris]
        story.append(_table(['KRI', 'Indicator', 'Risk', 'Current', 'Amber/Red', 'Status', 'Measured', 'Cadence'], rows,
                            [1.8 * cm, 5.4 * cm, 2.2 * cm, 1.8 * cm, 2.4 * cm, 1.6 * cm, 2.0 * cm, 1.8 * cm],
                            status_col=5, color_map=RAG))
    return story


def _compliance_section(org):
    from compliance.models import ControlFramework, AuditFinding, CorrectiveAction, Evidence
    from compliance.utils import calculate_compliance_score

    story = [Paragraph('2. Compliance Posture', H2)]
    rows = []
    for fw in ControlFramework.objects.filter(is_active=True).order_by('code'):
        sc = calculate_compliance_score(org, fw)
        if not sc['total_controls']:
            continue
        rows.append((fw.code, fw.name, sc['total_controls'], sc['implemented'], sc['partially_implemented'],
                     sc['not_implemented'], sc['not_applicable'], f"{sc['score']}%", 'Mandatory' if fw.is_mandatory else ''))
    story.append(_table(['Code', 'Framework', 'Controls', 'Impl.', 'Partial', 'Not impl.', 'N/A', 'Score', ''], rows,
                        [2.0 * cm, 5.6 * cm, 1.6 * cm, 1.3 * cm, 1.5 * cm, 1.7 * cm, 1.2 * cm, 1.5 * cm, 2.0 * cm]))

    today = timezone.localdate()
    findings = AuditFinding.objects.filter(audit__organization=org).exclude(status='closed').select_related('audit', 'assigned_to')
    story.append(Spacer(1, 8))
    story.append(Paragraph(f'Open audit findings: {findings.count()} '
                           f'(major NC: {findings.filter(finding_type="major_nc").count()}, '
                           f'overdue: {findings.filter(due_date__lt=today).count()})', BODY))
    rows = [(f.finding_id, f.title, f.get_finding_type_display(), f.audit.audit_id, f.get_status_display(),
             f.due_date or '-', f.assigned_to.get_full_name() if f.assigned_to else '-')
            for f in findings.order_by('due_date')[:20]]
    story.append(_table(['ID', 'Finding', 'Type', 'Audit', 'Status', 'Due', 'Owner'], rows,
                        [2.6 * cm, 5.6 * cm, 2.2 * cm, 2.2 * cm, 2.0 * cm, 1.8 * cm, 2.4 * cm]))

    cars = CorrectiveAction.objects.filter(organization=org, status__in=['open', 'in_progress', 'overdue', 'pending_verification'])
    ev = Evidence.objects.filter(organization=org)
    story.append(Spacer(1, 6))
    story.append(_kv([('Open corrective actions / overdue', f"{cars.count()} / {cars.filter(status='overdue').count()}"),
                      ('Evidence accepted / expiring in 30 days / expired',
                       f"{ev.filter(status='accepted').count()} / "
                       f"{ev.filter(status__in=['accepted', 'submitted'], valid_until__range=(today, today + timedelta(days=30))).count()} / "
                       f"{ev.filter(status='expired').count()}")]))
    return story


def _bcm_section(org):
    from django.conf import settings
    from bcm.models import BusinessFunction, BCPlan, DisasterRecoveryPlan, CrisisIncident
    from bcm.utils import capability_analysis, plan_test_status

    story = [Paragraph('3. Business Continuity & Recovery Capability', H2)]
    fns = BusinessFunction.objects.filter(organization=org, status='active', criticality__in=['critical', 'essential'])
    report = capability_analysis(org, fns, test_interval_days=settings.GRC_AUTOMATION.get('PLAN_TEST_INTERVAL_DAYS', 365))
    s = report['summary']
    story.append(_kv([('Critical/essential functions assessed', s['total']),
                      ('Recoverable within RTO and proven by exercise', s['covered']),
                      ('Requirement met but not proven (untested / unproven)', s['untested'] + s['unproven']),
                      ('Capability gap or no DR plan', s['gap'] + s['no_dr_plan']),
                      ('No BIA / no dependencies mapped', s['no_bia'] + s['no_dependencies'])]))
    story.append(Spacer(1, 6))
    rows = []
    for row in report['functions']:
        req = row['required'] or {}
        ach = row['achievable'] or {}
        prov = row['proven'] or {}
        rows.append((row['function']['function_id'], row['function']['name'], row['function']['criticality'],
                     f"{req.get('rto_hours', '-')}h / {req.get('rpo_hours', '-')}h",
                     f"{ach.get('rto_hours') or '-'}h / {ach.get('rpo_hours') or '-'}h",
                     f"{prov.get('rto_hours'):g}h" if prov.get('rto_hours') is not None else '-',
                     row['status'].replace('_', ' ').upper(), (row['issues'] or ['-'])[0][:90]))
    story.append(_table(['ID', 'Function', 'Crit.', 'Required RTO/RPO', 'Achievable', 'Proven', 'Status', 'Main issue'], rows,
                        [1.5 * cm, 3.6 * cm, 1.6 * cm, 2.4 * cm, 2.0 * cm, 1.5 * cm, 2.2 * cm, 4.2 * cm],
                        status_col=6, color_map={'covered': '#4CAF50', 'untested': '#FFC107', 'unproven': '#FF9800',
                                                 'gap': '#F44336', 'no dr plan': '#F44336', 'no bia': '#9E9E9E'}))

    plans = list(BCPlan.objects.filter(organization=org, status__in=['approved', 'active'])) + \
        list(DisasterRecoveryPlan.objects.filter(organization=org, status__in=['approved', 'active']))
    rows = []
    for p in plans:
        ts = plan_test_status(p)
        rows.append((p.plan_id, p.title, type(p).__name__.replace('DisasterRecoveryPlan', 'DR').replace('BCPlan', 'BC'),
                     p.last_tested_date or 'never', ts['next_test_date'] or '-', 'OVERDUE' if ts['overdue'] else ('due soon' if ts['needs_testing'] else 'ok')))
    story.append(Spacer(1, 8))
    story.append(Paragraph('Exercise programme', BODY))
    story.append(_table(['Plan', 'Title', 'Type', 'Last tested', 'Next test', 'Status'], rows,
                        [2.2 * cm, 7.0 * cm, 1.4 * cm, 2.4 * cm, 2.4 * cm, 2.0 * cm],
                        status_col=5, color_map={'overdue': '#F44336', 'due soon': '#FFC107'}))

    incidents = CrisisIncident.objects.filter(organization=org, reported_at__gte=timezone.now() - timedelta(days=365))
    story.append(Spacer(1, 6))
    story.append(_kv([('Incidents in the last 12 months / open', f"{incidents.count()} / {incidents.exclude(status__in=['resolved', 'closed']).count()}"),
                      ('Estimated losses (SAR)', f"{sum((i.financial_loss or 0) for i in incidents):,.0f}")]))
    return story


def build_report(organization, report_type='executive'):
    buf = io.BytesIO()
    doc = _doc(buf)
    titles = {'executive': 'Executive GRC Report', 'risk': 'Risk Report', 'compliance': 'Compliance Report',
              'bcm': 'Business Continuity Report'}
    title = titles.get(report_type, titles['executive'])
    story = [Paragraph(title, H1),
             Paragraph(f'{organization.name} &nbsp;|&nbsp; Reporting date {timezone.localdate():%d %B %Y}', SMALL),
             Spacer(1, 10)]
    if report_type in ('executive', 'risk'):
        story += _risk_section(organization)
    if report_type in ('executive', 'compliance'):
        if report_type == 'executive':
            story.append(PageBreak())
        story += _compliance_section(organization)
    if report_type in ('executive', 'bcm'):
        if report_type == 'executive':
            story.append(PageBreak())
        story += _bcm_section(organization)
    doc.build(story, onFirstPage=_header_footer(title, organization), onLaterPages=_header_footer(title, organization))
    return buf.getvalue()


def soa_pdf(data):
    """Statement of Applicability PDF from compliance.utils.build_soa_rows output."""
    buf = io.BytesIO()
    doc = _doc(buf)
    fw, s = data['framework'], data['summary']

    class _Org:  # minimal object for header
        name = data['organization']['name']

    title = f"Statement of Applicability - {fw['code']} {fw['version']}"
    story = [Paragraph(title, H1), Paragraph(f"{fw['name']} &nbsp;|&nbsp; {data['organization']['name']}", SMALL), Spacer(1, 8),
             _kv([('Controls in framework', s['total']), ('Applicable / not applicable', f"{s['applicable']} / {s['not_applicable']}"),
                  ('Exclusions missing a justification', s['missing_justification']),
                  ('Implemented / partially / not implemented / no record',
                   f"{s['implemented']} / {s['partially_implemented']} / {s['not_implemented']} / {s['no_record']}")]),
             Spacer(1, 10)]
    rows = [(r['control_id'], r['title'], 'Yes' if r['applicable'] else 'No',
             r['justification'] if not r['applicable'] else '',
             r['status'].replace('_', ' '), r['maturity_level'] if r['maturity_level'] is not None else '-',
             r['owner'] or '-', r['evidence_accepted']) for r in data['rows']]
    story.append(_table(['Control', 'Title', 'Applies', 'Justification for exclusion', 'Status', 'Mat.', 'Owner', 'Evid.'], rows,
                        [1.8 * cm, 5.0 * cm, 1.3 * cm, 3.8 * cm, 2.3 * cm, 1.0 * cm, 2.2 * cm, 1.0 * cm]))
    doc.build(story, onFirstPage=_header_footer(title, _Org), onLaterPages=_header_footer(title, _Org))
