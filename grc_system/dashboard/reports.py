"""
Board-ready PDF reports (pure-Python via reportlab, no system libraries needed).

  build_report(organization, report_type) -> bytes
     report_type: executive | risk | compliance | bcm
  soa_pdf(data) -> bytes   (data from compliance.utils.build_soa_rows)
"""
import io
from datetime import timedelta

from django.utils import timezone
from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.platypus import (
    Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle, PageBreak, KeepTogether,
)

LEVEL_COLORS = {'critical': '#F44336', 'high': '#FF5722', 'medium': '#FFC107', 'low': '#4CAF50'}
RAG = {'red': '#F44336', 'amber': '#FFC107', 'green': '#4CAF50', 'no_data': '#9E9E9E'}

_styles = getSampleStyleSheet()
H1 = ParagraphStyle('H1', parent=_styles['Title'], fontSize=20, spaceAfter=6, alignment=TA_LEFT)
H2 = ParagraphStyle('H2', parent=_styles['Heading2'], fontSize=13, spaceBefore=12, spaceAfter=6, textColor=colors.HexColor('#1e40af'))
BODY = ParagraphStyle('B', parent=_styles['BodyText'], fontSize=9, leading=12)
SMALL = ParagraphStyle('S', parent=BODY, fontSize=8, leading=10, textColor=colors.HexColor('#555555'))
CELL = ParagraphStyle('C', parent=BODY, fontSize=8, leading=10)


def _p(text, style=CELL):
    return Paragraph(str(text if text is not None else '-').replace('\n', '<br/>'), style)


def _table(header, rows, widths=None, zebra=True, status_col=None, color_map=None):
    data = [[_p(f'<b>{h}</b>') for h in header]] + [[_p(c) for c in r] for r in rows] if rows else \
           [[_p(f'<b>{h}</b>') for h in header], [_p('No records')] + [''] * (len(header) - 1)]
    t = Table(data, colWidths=widths, repeatRows=1)
    style = [
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#1e40af')),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('GRID', (0, 0), (-1, -1), 0.25, colors.HexColor('#cccccc')),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('LEFTPADDING', (0, 0), (-1, -1), 4), ('RIGHTPADDING', (0, 0), (-1, -1), 4),
    ]
    if zebra:
        for i in range(1, len(data)):
            if i % 2 == 0:
                style.append(('BACKGROUND', (0, i), (-1, i), colors.HexColor('#f5f7fb')))
    if status_col is not None and color_map and rows:
        for i, r in enumerate(rows, start=1):
            c = color_map.get(str(r[status_col]).lower())
            if c:
                style.append(('BACKGROUND', (status_col, i), (status_col, i), colors.HexColor(c)))
                style.append(('TEXTCOLOR', (status_col, i), (status_col, i), colors.white))
    t.setStyle(TableStyle(style))
    return t


def _kv(pairs):
    t = Table([[_p(f'<b>{k}</b>'), _p(v)] for k, v in pairs], colWidths=[6 * cm, 10 * cm])
    t.setStyle(TableStyle([('GRID', (0, 0), (-1, -1), 0.25, colors.HexColor('#dddddd')),
                           ('BACKGROUND', (0, 0), (0, -1), colors.HexColor('#eef2ff'))]))
    return t


def _header_footer(title, organization):
    def draw(canvas, doc):
        canvas.saveState()
        canvas.setFont('Helvetica', 8)
        canvas.setFillColor(colors.HexColor('#666666'))
        canvas.drawString(2 * cm, A4[1] - 1.2 * cm, f'{organization.name} - {title}')
        canvas.drawRightString(A4[0] - 2 * cm, A4[1] - 1.2 * cm, timezone.localtime().strftime('%Y-%m-%d %H:%M'))
        canvas.drawString(2 * cm, 1.2 * cm, 'CONFIDENTIAL - Generated by the GRC System')
        canvas.drawRightString(A4[0] - 2 * cm, 1.2 * cm, f'Page {doc.page}')
        canvas.restoreState()
    return draw


def _doc(buf):
    return SimpleDocTemplate(buf, pagesize=A4, leftMargin=2 * cm, rightMargin=2 * cm, topMargin=2 * cm, bottomMargin=2 * cm)


