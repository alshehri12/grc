<template>
    <div class="reports-page">
        <div class="page-header">
            <div>
                <h1>{{ $t('reports.title') }}</h1>
                <p>تقارير مجلس الإدارة واللجان - Board & committee reports (PDF)</p>
            </div>
        </div>

        <div class="report-grid">
            <Card v-for="r in reportTypes" :key="r.type" class="report-card">
                <template #title><i :class="r.icon" style="margin-right:.5rem"></i>{{ r.title }}</template>
                <template #subtitle>{{ r.title_ar }}</template>
                <template #content>
                    <p class="text-muted">{{ r.description }}</p>
                    <Button :label="'Download PDF'" icon="pi pi-file-pdf" @click="download(r.type)" :loading="busy === r.type" />
                </template>
            </Card>
        </div>

        <Card class="mt">
            <template #title>Report archive</template>
            <template #content>
                <DataTable :value="archive" paginator :rows="10" :loading="loading">
                    <Column field="title" header="Report" />
                    <Column field="generated_by_name" header="Generated by" />
                    <Column field="generated_at" header="Generated at"><template #body="{ data }">{{ data.generated_at ? new Date(data.generated_at).toLocaleString() : '-' }}</template></Column>
                    <Column field="status" header="Status"><template #body="{ data }"><Tag :severity="data.status === 'completed' ? 'success' : 'danger'">{{ data.status }}</Tag></template></Column>
                    <Column header=""><template #body="{ data }"><a v-if="data.file" :href="data.file" target="_blank" class="p-button p-button-text p-button-sm"><i class="pi pi-download"></i></a></template></Column>
                </DataTable>
            </template>
        </Card>
    </div>
</template>

<script setup>
import { ref, onMounted } from 'vue'
import Card from 'primevue/card'
import Button from 'primevue/button'
import DataTable from 'primevue/datatable'
import Column from 'primevue/column'
import Tag from 'primevue/tag'
import { useToast } from 'primevue/usetoast'
import { dashboardApi } from '@/api'
import { useAppStore } from '@/stores/app'

const appStore = useAppStore()
const toast = useToast()
const busy = ref(null)
const loading = ref(false)
const archive = ref([])

const reportTypes = [
    { type: 'executive', icon: 'pi pi-briefcase', title: 'Executive GRC Report', title_ar: 'التقرير التنفيذي للحوكمة والمخاطر والامتثال',
      description: 'One pack for the board: risk profile and appetite, KRIs, compliance per framework, open findings, recovery capability and exercise programme.' },
    { type: 'risk', icon: 'pi pi-exclamation-triangle', title: 'Risk Report', title_ar: 'تقرير المخاطر',
      description: 'Inherent vs residual distribution, risks outside appetite with treatment status, top exposures and KRI status.' },
    { type: 'compliance', icon: 'pi pi-check-square', title: 'Compliance Report', title_ar: 'تقرير الامتثال',
      description: 'Compliance score per framework (NCA ECC, ISO 27001, SAMA, PDPL), open findings and corrective actions, evidence status.' },
    { type: 'bcm', icon: 'pi pi-shield', title: 'Business Continuity Report', title_ar: 'تقرير استمرارية الأعمال',
      description: 'Recovery capability (required vs achievable vs proven RTO), exercise programme status and incidents of the last 12 months.' },
]

const download = async (type) => {
    busy.value = type
    try {
        const orgId = await appStore.ensureOrganization()
        const res = await dashboardApi.reports.boardPack(orgId, type)
        const url = URL.createObjectURL(new Blob([res.data], { type: 'application/pdf' }))
        const a = document.createElement('a'); a.href = url; a.download = `${type}-report.pdf`; a.click(); URL.revokeObjectURL(url)
        loadArchive()
    } catch (e) {
        toast.add({ severity: 'error', summary: 'Error', detail: 'Failed to generate the report', life: 4000 })
    } finally { busy.value = null }
}
const loadArchive = async () => {
    loading.value = true
    try {
        const orgId = await appStore.ensureOrganization()
        const res = await dashboardApi.reports.list({ organization: orgId })
        archive.value = res.data.results || res.data
    } finally { loading.value = false }
}
onMounted(loadArchive)
</script>

